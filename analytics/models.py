from django.db import models
from accounts.models import CustomUser


class SiteVisit(models.Model):
    """Track page visits for analytics dashboard."""
    path = models.CharField(max_length=500)
    ip_address = models.GenericIPAddressField(null=True, blank=True)
    user = models.ForeignKey(CustomUser, on_delete=models.SET_NULL, null=True, blank=True)
    session_key = models.CharField(max_length=100, blank=True)
    user_agent = models.TextField(blank=True)
    referrer = models.TextField(blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-created_at']
        verbose_name = 'Site Visit'
        verbose_name_plural = 'Site Visits'

    def __str__(self):
        return f"{self.path} — {self.created_at.strftime('%Y-%m-%d %H:%M')}"


class SalesReport(models.Model):
    """Daily aggregated sales snapshot (can be generated by a cron/management command)."""
    date = models.DateField(unique=True)
    total_orders = models.PositiveIntegerField(default=0)
    total_revenue = models.DecimalField(max_digits=12, decimal_places=2, default=0)
    total_items_sold = models.PositiveIntegerField(default=0)
    new_customers = models.PositiveIntegerField(default=0)
    cancelled_orders = models.PositiveIntegerField(default=0)
    refunded_amount = models.DecimalField(max_digits=12, decimal_places=2, default=0)
    average_order_value = models.DecimalField(max_digits=10, decimal_places=2, default=0)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['-date']
        verbose_name = 'Sales Report'
        verbose_name_plural = 'Sales Reports'

    def __str__(self):
        return f"Sales Report — {self.date} (₹{self.total_revenue})"


class AdminActivityLog(models.Model):
    """Log every significant admin action for audit trail."""
    ACTION_TYPES = [
        ('create', 'Created'),
        ('update', 'Updated'),
        ('delete', 'Deleted'),
        ('login', 'Logged In'),
        ('logout', 'Logged Out'),
        ('export', 'Exported Data'),
        ('status_change', 'Status Changed'),
        ('refund', 'Issued Refund'),
        ('other', 'Other'),
    ]
    admin_user = models.ForeignKey(
        CustomUser, on_delete=models.SET_NULL, null=True, blank=True,
        related_name='activity_logs'
    )
    action_type = models.CharField(max_length=20, choices=ACTION_TYPES, default='other')
    model_name = models.CharField(max_length=100, blank=True)
    object_id = models.CharField(max_length=100, blank=True)
    object_repr = models.CharField(max_length=500, blank=True)
    description = models.TextField(blank=True)
    ip_address = models.GenericIPAddressField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-created_at']
        verbose_name = 'Activity Log'
        verbose_name_plural = 'Activity Logs'

    def __str__(self):
        return f"{self.admin_user} — {self.get_action_type_display()} {self.model_name} at {self.created_at.strftime('%Y-%m-%d %H:%M')}"


class NewsletterSubscriber(models.Model):
    """Store newsletter subscriptions with source tracking."""
    STATUS_CHOICES = [
        ('active', 'Active'),
        ('unsubscribed', 'Unsubscribed'),
        ('bounced', 'Bounced'),
    ]
    SOURCE_CHOICES = [
        ('signup', 'Signup Form'),
        ('checkout', 'Checkout'),
        ('footer', 'Footer'),
        ('popup', 'Popup'),
        ('other', 'Other'),
    ]
    email = models.EmailField(unique=True)
    user = models.OneToOneField(
        CustomUser, on_delete=models.SET_NULL, null=True, blank=True,
        related_name='newsletter_entry'
    )
    first_name = models.CharField(max_length=100, blank=True)
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default='active')
    source = models.CharField(max_length=20, choices=SOURCE_CHOICES, default='signup')
    subscribed_at = models.DateTimeField(auto_now_add=True)
    unsubscribed_at = models.DateTimeField(null=True, blank=True)
    ip_address = models.GenericIPAddressField(null=True, blank=True)
    notes = models.TextField(blank=True)

    class Meta:
        ordering = ['-subscribed_at']
        verbose_name = 'Newsletter Subscriber'
        verbose_name_plural = 'Newsletter Subscribers'

    def __str__(self):
        return f"{self.email} ({self.get_status_display()})"


class LowStockAlert(models.Model):
    """Track products that have fallen below a stock threshold."""
    STATUS_CHOICES = [
        ('open', 'Open'),
        ('acknowledged', 'Acknowledged'),
        ('restocked', 'Restocked'),
        ('dismissed', 'Dismissed'),
    ]
    from store.models import Product
    product = models.ForeignKey(
        'store.Product', on_delete=models.CASCADE, related_name='stock_alerts'
    )
    stock_at_alert = models.PositiveIntegerField()
    threshold = models.PositiveIntegerField(default=10)
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default='open')
    acknowledged_by = models.ForeignKey(
        CustomUser, on_delete=models.SET_NULL, null=True, blank=True,
        related_name='acknowledged_alerts'
    )
    acknowledged_at = models.DateTimeField(null=True, blank=True)
    notes = models.TextField(blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['-created_at']
        verbose_name = 'Low Stock Alert'
        verbose_name_plural = 'Low Stock Alerts'

    def __str__(self):
        return f"Alert: {self.product.name} — {self.stock_at_alert} left"
